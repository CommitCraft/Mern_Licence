<?php

declare(strict_types=1);

namespace App\Services;

use App\Exceptions\LicenceException;

final class EnvironmentWriter
{
    private string $envFilePath;

    private const ALLOWED_KEYS = [
        'APP_ENV',
        'APP_NAME',
        'APP_URL',
        'APP_TIMEZONE',
        'APP_KEY',
        'DB_HOST',
        'DB_PORT',
        'DB_NAME',
        'DB_USER',
        'DB_PASSWORD',
        'LICENCE_SERVER_URL',
        'LICENCE_PRODUCT_CODE',
        'LICENCE_PUBLIC_KEY_PATH',
        'LICENCE_PRIVATE_KEY_PATH',
        'LICENCE_INSTALLATION_PATH',
        'LICENCE_CERTIFICATE_PATH',
        'LICENCE_VALIDATION_STATE_PATH',
        'LICENCE_VALIDATION_INTERVAL_HOURS',
        'LICENCE_OFFLINE_GRACE_DAYS',
        'APP_VERSION',
        'SETUP_COMPLETED'
    ];

    public function __construct(?string $customEnvPath = null)
    {
        $this->envFilePath = $customEnvPath ?? __DIR__ . '/../../.env';
    }

    public function validateWritablePath(): void
    {
        $dir = dirname($this->envFilePath);
        if (!is_dir($dir) || !is_writable($dir)) {
            throw new LicenceException("Environment directory '{$dir}' is not writable.", 'ENV_DIR_NOT_WRITABLE', 500);
        }

        if (file_exists($this->envFilePath) && !is_writable($this->envFilePath)) {
            throw new LicenceException(".env file exists but is not writable.", 'ENV_FILE_NOT_WRITABLE', 500);
        }
    }

    public function build(array $config): string
    {
        $lines = [
            '# System Environment Configuration — Generated by Installation Wizard',
            '# Created: ' . date('c'),
            ''
        ];

        foreach (self::ALLOWED_KEYS as $key) {
            if (array_key_exists($key, $config)) {
                $val = (string)$config[$key];
                $escaped = $this->escapeValue($val);
                $lines[] = "{$key}={$escaped}";
            }
        }

        return implode("\n", $lines) . "\n";
    }

    public function writeAtomically(string $content): void
    {
        $this->validateWritablePath();

        $tmpPath = $this->envFilePath . '.tmp';
        $fp = fopen($tmpPath, 'w');
        if ($fp === false) {
            throw new LicenceException('Failed to open temporary .env file for writing.', 'ENV_WRITE_FAILED', 500);
        }

        try {
            if (flock($fp, LOCK_EX)) {
                fwrite($fp, $content);
                fflush($fp);
                flock($fp, LOCK_UN);
            }
        } finally {
            fclose($fp);
        }

        chmod($tmpPath, 0600);

        if (!rename($tmpPath, $this->envFilePath)) {
            throw new LicenceException('Failed to rename atomic .env file.', 'ENV_RENAME_FAILED', 500);
        }

        chmod($this->envFilePath, 0600);
    }

    private function escapeValue(string $val): string
    {
        // Boolean strings or numbers do not require quotes
        if (in_array(strtolower($val), ['true', 'false', 'null'], true) || is_numeric($val)) {
            return $val;
        }

        // If contains spaces, quotes, hashes, or special chars, enclose in double quotes and escape internal quotes
        if (preg_match('/[ "#\'$:=\\\\]/', $val)) {
            $escaped = str_replace(['\\', '"', '$'], ['\\\\', '\"', '\\$'], $val);
            return '"' . $escaped . '"';
        }

        return $val;
    }
}
